//! Text rasterization and alpha compositing for watermark overlays.
//!
//! tpt-wasmforge's `add_text_watermark` blends directly onto an opaque
//! destination and only at fixed positions, which can't express tiling or a
//! reusable overlay buffer — so the engine rasterizes text itself (same 6×8
//! bitmap font as `tpt-media-image::watermark`, keeping the two renders
//! visually identical) and composites through one source-over path used for
//! both text and logo overlays. Codec + bilinear resize stay in wasmforge.

use crate::spec::Position;
use crate::{ForgeResult, ImageBuffer};

/// Rasterize a single line of text into a transparent RGBA buffer, `height_px`
/// being the glyph height in pixels (the 6×8 font is scaled by whole factors,
/// so the actual height is the nearest multiple of 8).
pub fn text_overlay(text: &str, height_px: u32, color: [u8; 3]) -> ImageBuffer {
    let scale = (height_px / 8).max(1);
    let glyph_w = 6 * scale;
    let glyph_h = 8 * scale;
    let chars: Vec<char> = text.chars().collect();
    let width = (chars.len() as u32 * glyph_w).max(1);
    let mut out = ImageBuffer::new(width, glyph_h).expect("overlay dims are non-zero");
    for (ci, ch) in chars.iter().enumerate() {
        let bitmap = glyph(*ch);
        let cx = ci as u32 * glyph_w;
        for row in 0..8u32 {
            let bits = bitmap[row as usize];
            for col in 0..6u32 {
                if (bits >> (5 - col)) & 1 == 1 {
                    for sy in 0..scale {
                        for sx in 0..scale {
                            out.set_pixel(cx + col * scale + sx, row * scale + sy, [
                                color[0], color[1], color[2], 255,
                            ]);
                        }
                    }
                }
            }
        }
    }
    out
}

/// Decode-independent logo overlay: scale the logo so its larger side is
/// `scale_frac * min_dim` (aspect preserved, never zero), via wasmforge's
/// bilinear resize.
pub fn logo_overlay(
    logo: &ImageBuffer,
    scale_frac: f32,
    min_dim: u32,
) -> ForgeResult<ImageBuffer> {
    let target = (scale_frac * min_dim as f32).round().max(4.0) as u32;
    let (tw, th) = if logo.width >= logo.height {
        (target, (target as f64 * logo.height as f64 / logo.width as f64).round().max(1.0) as u32)
    } else {
        ((target as f64 * logo.width as f64 / logo.height as f64).round().max(1.0) as u32, target)
    };
    tpt_media_image::resize(logo, tw, th)
}

/// Source-over composite of `overlay` onto `dst` at `(x, y)` — negative
/// origins and overhangs are clipped, `opacity` multiplies the overlay's own
/// alpha. Output alpha is a proper source-over mix (not just dst alpha kept),
/// so watermarked PNGs with transparent regions survive correctly.
pub fn composite(dst: &mut ImageBuffer, overlay: &ImageBuffer, x: i64, y: i64, opacity: f32) {
    let opacity = opacity.clamp(0.0, 1.0) as f64;
    for oy in 0..overlay.height as i64 {
        let dy = y + oy;
        if dy < 0 || dy >= dst.height as i64 {
            continue;
        }
        for ox in 0..overlay.width as i64 {
            let dx = x + ox;
            if dx < 0 || dx >= dst.width as i64 {
                continue;
            }
            let [sr, sg, sb, sa] = overlay.get_pixel(ox as u32, oy as u32);
            let src_a = (sa as f64 / 255.0) * opacity;
            if src_a <= 0.0 {
                continue;
            }
            let [dr, dg, db, da] = dst.get_pixel(dx as u32, dy as u32);
            let dst_a = da as f64 / 255.0;
            let out_a = src_a + dst_a * (1.0 - src_a);
            if out_a <= 0.0 {
                continue;
            }
            let mix = |s: u8, d: u8| -> u8 {
                ((s as f64 * src_a + d as f64 * dst_a * (1.0 - src_a)) / out_a)
                    .round()
                    .clamp(0.0, 255.0) as u8
            };
            dst.set_pixel(dx as u32, dy as u32, [
                mix(sr, dr),
                mix(sg, dg),
                mix(sb, db),
                (out_a * 255.0).round().clamp(0.0, 255.0) as u8,
            ]);
        }
    }
}

/// Margin for single placements: a fixed 8 px vanishes on 6000 px photos, so
/// scale with the image, clamped to sane bounds.
fn margin(dst: &ImageBuffer) -> u32 {
    (dst.width.min(dst.height) / 40).clamp(8, 80)
}

/// Place `overlay` at `position` with the standard margin.
pub fn composite_positioned(
    dst: &mut ImageBuffer,
    overlay: &ImageBuffer,
    position: Position,
    opacity: f32,
) {
    let m = margin(dst) as i64;
    let (ox, oy) = match position {
        Position::TopLeft => (m, m),
        Position::TopRight => (dst.width as i64 - overlay.width as i64 - m, m),
        Position::Center => (
            (dst.width as i64 - overlay.width as i64) / 2,
            (dst.height as i64 - overlay.height as i64) / 2,
        ),
        Position::BottomLeft => (m, dst.height as i64 - overlay.height as i64 - m),
        Position::BottomRight => (
            dst.width as i64 - overlay.width as i64 - m,
            dst.height as i64 - overlay.height as i64 - m,
        ),
    };
    composite(dst, overlay, ox, oy, opacity);
}

/// Tile `overlay` across `dst` in a grid with `gap_frac` (of the smaller
/// dimension) between tiles, half-gap inset so edge tiles are symmetric.
pub fn composite_tiled(dst: &mut ImageBuffer, overlay: &ImageBuffer, opacity: f32, gap_frac: f32) {
    let gap = (gap_frac.clamp(0.0, 1.0) * dst.width.min(dst.height) as f32) as i64;
    let step_x = overlay.width as i64 + gap;
    let step_y = overlay.height as i64 + gap;
    if step_x <= 0 || step_y <= 0 {
        return;
    }
    let mut y = gap / 2;
    while y < dst.height as i64 {
        let mut x = gap / 2;
        while x < dst.width as i64 {
            composite(dst, overlay, x, y, opacity);
            x += step_x;
        }
        y += step_y;
    }
}

// --- 6×8 bitmap font (ASCII 32–126), identical to tpt-wasmforge's
// tpt-media-image::watermark table (MIT OR Apache-2.0, TPT Solutions) so
// engine-rendered text matches the wasmforge renderer pixel for pixel.
// Each glyph is 8 rows × 6 bits (MSB = leftmost pixel).

fn glyph(ch: char) -> [u8; 8] {
    // The proof watermark's signature character: the wasmforge table only
    // covers ASCII, so © gets a dedicated glyph instead of collapsing into
    // a space.
    if ch == '\u{00A9}' {
        return [0x1E, 0x21, 0x2D, 0x29, 0x2D, 0x21, 0x1E, 0x00];
    }
    let idx = ch as usize;
    if (32..=126).contains(&idx) {
        FONT_DATA[idx - 32]
    } else {
        FONT_DATA[0] // space for unknowns
    }
}

